from facebook_scraper import get_posts
import pandas as pd
import time

# Khởi tạo danh sách lưu trữ dữ liệu
post_data = []

# Tên người dùng hoặc ID của trang UIT Confessions
page_name = 'UITConfessions'

print(f"Đang tiến hành crawl dữ liệu từ page {page_name}...")

try:
    # pages=10: số lượng trang bạn muốn cuộn xuống (tùy chỉnh số lượng này)
    # options={"comments": False}: Tắt crawl comment để tập trung lấy bài confession nhanh hơn
    for post in get_posts(page_name, pages=10, cookies='www.facebook.com_cookies.txt', options={"comments": False}):

        # Chỉ lưu các bài viết có nội dung văn bản
        if post['text']:
            post_data.append({
                'post_id': post['post_id'],
                'time': post['time'],
                'text': post['text'],
                'likes': post['likes'],
                'comments_count': post['comments']
            })
            print(f"Đã lấy bài viết ID: {post['post_id']}")

        # Tạm nghỉ 3 giây giữa các lần tải trang để tránh bị Facebook khóa tài khoản
        time.sleep(3)

except Exception as e:
    print("Có lỗi xảy ra trong quá trình crawl:", e)

# Chuyển đổi danh sách dữ liệu thành cấu trúc bảng DataFrame
df = pd.DataFrame(post_data)
print(f"\nTổng cộng đã thu thập được {len(df)} bài viết.")

# Lưu kết quả ra file CSV để sử dụng cho bước tiền xử lý
df.to_csv('uit_confessions_raw.csv', index=False, encoding='utf-8-sig')
print("Đã lưu toàn bộ dữ liệu vào file 'uit_confessions_raw.csv'.")